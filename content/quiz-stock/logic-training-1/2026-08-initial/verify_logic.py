# 16-2(v2): 機械検証できる問題の数値・構造チェック
# なぞなぞ・とんち(朝・夜の大半)は「定番の想定解」であり機械検証の対象外 → 人間レビューが砦。
# ここでは昼のフェルミ推定の算数と、夜の算数的ひっかけの整合だけを検証する。
checks = []


def check(name, cond, note=""):
    checks.append((name, cond, note))


# ---- 昼(L3)フェルミ推定の算数 ----
check("B01 睡眠25年", abs(80 * 8 / 24 - 26.7) < 0.1, "80年×8h/24h≈26.7年 → 約25年")
walk_km = 7000 * 0.7 / 1000 * 365 * 80
check("B02 歩行15万km", 140_000 < walk_km < 150_000, f"{walk_km:,.0f}km(地球1周4万kmの3周半)")
check("B03 心拍10万回", 95_000 < 70 * 60 * 24 < 105_000, f"{70*60*24:,}回/日")
blink = 15 * 60 * 16 * 365 * 80
check("B04 まばたき4億回", 3.5e8 < blink < 4.5e8, f"{blink:,.0f}回/一生")
hair = 100_000 / (4.5 * 365)
check("B05 抜け毛50〜100本", 50 < hair < 100, f"{hair:.0f}本/日(寿命4.5年)")
check("B06 食事9万回", 85_000 < 3 * 365 * 80 < 90_000, f"{3*365*80:,}回")
commute_days = 1 * 240 * 40 / 24
check("B07 通勤1年", 380 < commute_days < 420, f"{commute_days:.0f}日≈1.1年")
check("B08 電車2000人", 1_900 < 150 * 1.4 * 10 < 2_200, f"{150*1.4*10:,.0f}人")
check("B09 缶コーヒー2000万", 60_000_000 / 3 == 20_000_000, "6000万×1/3")
parcel = 1.2e8 * 30 / 365
check("B10 宅配1000万個", 9e6 < parcel < 1.1e7, f"{parcel:,.0f}個/日")
check("B11 自販機400万台", 1.2e8 / 30 == 4e6, "1.2億÷30")
birth = 700_000 / 365
check("B12 赤ちゃん1900人", 1_800 < birth < 2_100, f"{birth:.0f}人/日")
curry = 2 * 12 * 70
check("B13 カレー1700皿", 1_600 < curry < 1_800, f"{curry}皿")
phone_days = 3.5 * 365 / 24
check("B14 スマホ50日", 48 < phone_days < 58, f"{phone_days:.0f}日/年")

# ---- 夜(L1)算数的ひっかけの整合 ----
check("C08 2父2息子=3人", True, "祖父・父・息子(父が2役)で「父2・息子2」を充足")
check("C09 コイン110円", 100 + 10 == 110 and "100円玉" != "10円玉", "「片方(100円玉)は10円玉ではない」は真")
check("C10 ろうそく3本", True, "点火7本は燃え尽き、消えた3本のみ現存(想定解)")

# ---- 文字なぞなぞの文字数検証 ----
check("A03 せかいの真ん中", "せかい"[1] == "か", "真ん中の文字=か")
check("A11 と の数", "おとうと".count("と") == 2 and "いもうと".count("と") == 1)
check("A12 ち の数", "いちにち".count("ち") == 2 and "いちねん".count("ち") == 1)

ng = [c for c in checks if not c[1]]
for name, ok, note in checks:
    print(f"{'OK' if ok else 'NG'} {name}: {note}")
print(f"\n{'全チェック OK' if not ng else f'NG {len(ng)} 件'}(なぞなぞ・とんちの想定解は人間レビューで確認)")
raise SystemExit(1 if ng else 0)
