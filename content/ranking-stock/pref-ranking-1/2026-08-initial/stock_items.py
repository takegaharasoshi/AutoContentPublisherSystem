# 各ネタの ranking_data / source_note の数値は **手書きしない**。data/<data>.json
# （県換算ツーリング common/convert.py の出力、または一次情報から機械抽出したもの）を
# generate.py が読み込んで組み立てる。ここに書くのは「表示文言」と「ナレーション台本」だけ。
#
# フィールド仕様（docs/app/data-model.html セクション 4.13 /
#                docs/app/generators/ranking-prebuilt.html セクション 8.3）:
#   content_fields = hook / trivia / source_display / result_list / value_suffix / subtitle / bg_motif
#     - result_list と value_suffix はツーリングが data/*.json から機械整形する（手書き禁止）
#   narration = 尺別 cue 台本（"20s" / "30s"）
#
# ナレーション cue の暫定予算（アンカーの確定値は 17-4 のタイムライン定数が正。
# ここでは 17-3 で見直したシーン構成から機械的に割り付けた暫定値で執筆し、
# ビルド時の VOICEVOX 実測長による予算検査〔方式設計書 8.3〕で最終確認する）:
#
#   20 秒版 600f | intro 2.5s / teaser 2.0s / r5〜r2 各 2.0s
#                | r1_call 2.5s / r1_name 2.0s / outro 3.0s
#   30 秒版 900f | intro 3.5s / teaser 2.0s / r5〜r2 各 2.0s / r*_comment 各 1.5s
#                | r1_call 3.0s / r1_name 2.5s / closing 5.0s（結果総覧 3.0s + 締め 2.0s をまたぐ）
#
#   17-3 の変更点: ①5〜2 位は呼び込み（r*_call）と県名（r*_name）を 1 本の cue
#   （`r5`〜`r2` = 「まずは5位、埼玉県！」の形）に統合した。1 位のみタメ（r1_call）と
#   発表（r1_name）を分けたままにする（タメが演出の核のため）②intro の直後に視聴者へ
#   予想を促す煽り cue `teaser` を新設した（全ネタ必須）。この 2 点で捻出した尺が teaser の
#   原資であり、20 秒版・30 秒版とも総尺は変わらない。③20 秒版の outro は
#   「みんなはわかったかな？」で全ネタ共通（予想の答え合わせで閉じる）。30 秒版は県名を
#   並べるだけの recap をやめ、recap + outro を **ネタの締めくくりを語る closing 1 本**に
#   統合した（「納豆好きの地図は、きれいに北へ寄ってるな！」の類。trivia の核を口語で言う）。
#
#   文字数上限は「予算秒 × 5 文字」（句読点・感嘆符・記号は数えない）。validate.py が検査する。
#
# キャラクター: 表彰台五郎（お祭り実況・元気・人懐っこい。声 = VOICEVOX 白上虎太郎）
#   ネタ選定基準「下位の県の人が笑って自虐できるか」に従い、下位順位には一切言及しない。
#   文体は hook / trivia も含めて **五郎の一人称（タメ口の実況調）** で統一する
#   （17-3 決定。セット別設計書 pref-ranking-1.html セクション 5）。キャプションだけ
#   中立の解説調にすると書き手が入れ替わって見えるため。数値・単位・出典は口調を
#   変えても原文どおりに書き、信頼性は直下の出典行が担保する。

