YESNO_OPENERS = {
    "yes": "はい！",
    "no": "いいえ。",
    "irrelevant": "関係ないよ。",
}
LEAK_GUARD_TEXT = "コメントありがとう！"


def _select(options: tuple[str, ...], comment_id: str) -> str:
    digest = hashlib.sha1(str(comment_id).encode("utf-8")).digest()
    return options[int.from_bytes(digest[:8], "big") % len(options)]


def pick(kind: str, comment_id: str) -> str | None:
    """コメント ID の SHA-1 で定型文を選ぶ（templates.py と同じ選び方）。"""
    options = TEMPLATES.get(kind)
    if options is None:
        return None
    return _select(options, comment_id)


def split_reply(comment_id: str) -> str:
    """Choose one disclosure-safe message for a split decision."""
    return _select(CONSENSUS_SPLIT, comment_id)


def bare_term_reply(term: str, comment_id: str) -> str:
    """Ask what the comment's original term refers to."""
    return _select(BARE_TERM_QUESTIONS, comment_id).format(term=term)


def yesno_reply(answer: str, comment_id: str) -> str:
    """判定語と一言（空 = 判定語だけ）を組み立てる。"""
    return YESNO_OPENERS.get(answer, YESNO_OPENERS["irrelevant"]) + (pick("q_yesno", comment_id) or "")


def correct_reply(reveal_text: str) -> str:
    """正解宣言に開示文を付ける。"""
    return CORRECT_PREFIX + reveal_text
